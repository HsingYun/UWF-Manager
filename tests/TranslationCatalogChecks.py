#!/usr/bin/env python3
"""Validate application catalogs, optionally against a fresh lupdate catalog."""
import argparse
import collections
import pathlib
import re
import sys
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from html.parser import HTMLParser

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHARED = {'Microsoft Defender', 'System Center Endpoint Protection', '#'}
IDENTICAL = {
    'de': {'OK', 'Filter', 'Overlay', 'Name', '✓ Filter: %1', 'Tag', 'Status'},
    'es': {'No'},
    'fr': {'OK', 'Type', 'Overlay', 'Message'},
    'id': {'OK', 'File…', 'Folder…', 'Filter', 'Overlay', 'Data', '(Default)', 'Log', '✓ Filter: %1', 'Tag', 'Status', 'Detail'},
    'it': {'OK', 'No', 'File…', 'Overlay', 'Tag'},
    'ja': {'OK'},
    'nl': {'OK', 'Filter', 'Type', 'Overlay', '✓ Filter: %1', 'Tag', 'Status', 'Background Intelligent Transfer Service (BITS)', '── Batch %1 ──'},
    'pl': {'OK', 'Folder…', 'Tag'},
    'pt_BR': {'OK', 'Log', 'Tag', 'Status'},
    'pt_PT': {'OK', 'Tag', 'Status'},
    'vi': {'OK'},
}
TOKENS = re.compile(r'%(?:L?\d+|n|ProgramFiles%)')
LOCAL_QT_LOCALES = {'id', 'vi'}
LITERALS = (
    r'HKLM\SOFTWARE\HsingYun\UWF Manager',
    r'HKLM\SECURITY\Policy\Secrets\$MACHINE.ACC',
    r'HKLM\BCD00000000', r'HKLM\SYSTEM', r'HKLM\SOFTWARE', r'HKLM\SAM', r'HKLM\SECURITY', r'HKLM\COMPONENTS',
    r'HKLM\SYSTEM\CurrentControlSet\Services\UWFManagerEnhanced',
    r'%ProgramFiles%\UWF Manager\Service\UWF.exe',
    r'Interfaces\{GUID}\{GUID}.xml', 'UWF_Overlay.GetOverlayFiles', 'DomainSecretKey', 'TSCAL', 'NTUSER.DAT',
    'bootstatuspolicy', 'ignoreallfailures',
)


class Markup(HTMLParser):
    def __init__(self, text):
        super().__init__(convert_charrefs=False)
        self.stack = []
        self.structure = collections.Counter()
        self.feed(text)
        if self.stack:
            raise ValueError('unclosed rich-text tags')

    def handle_starttag(self, tag, attrs):
        self.structure[(tag, tuple(sorted(attrs)))] += 1
        if tag not in {'br', 'hr', 'img', 'meta', 'link', 'input'}:
            self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.structure[(tag, tuple(sorted(attrs)))] += 1

    def handle_endtag(self, tag):
        if not self.stack or self.stack.pop() != tag:
            raise ValueError(f'unbalanced rich-text tag {tag}')


def catalog(path):
    root = ET.parse(path).getroot()
    messages = {}
    for context in root.findall('context'):
        for message in context.findall('message'):
            key = (context.findtext('name'), message.findtext('source'), message.findtext('comment', ''))
            if key in messages:
                raise ValueError(f'duplicate translation key: {key}')
            messages[key] = message
    return root, messages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lupdate', type=pathlib.Path, help='extract current source strings before checking')
    parser.add_argument('--source-catalog', type=pathlib.Path, help='TS file freshly generated by lupdate')
    parser.add_argument('--qt-source', type=pathlib.Path, help='local Qt source tree for upstream context comparison')
    args = parser.parse_args()
    codes = re.findall(r'Language\{Lang::\w+, "([^"]+)"_L1', (ROOT / 'src/ui/I18n.cpp').read_text(encoding='utf-8'))
    codes = [code for code in codes if code != 'en']
    _, reference = catalog(ROOT / 'resources/i18n/zh_CN.ts')
    failures = []
    cmake = (ROOT / 'CMakeLists.txt').read_text(encoding='utf-8')
    configured = re.search(r'set\(UWF_I18N_LOCALES ([^)]+)\)', cmake).group(1).split()
    if set(configured) != set(codes):
        failures.append('runtime and CMake language lists differ')
    extracted_path = args.source_catalog
    temporary = tempfile.TemporaryDirectory() if args.lupdate else None
    try:
        if args.lupdate:
            extracted_path = pathlib.Path(temporary.name) / 'source.ts'
            subprocess.run([str(args.lupdate), str(ROOT / 'main.cpp'), str(ROOT / 'src'),
                            '-no-obsolete', '-locations', 'none', '-ts', str(extracted_path)], check=True)
        extracted = catalog(extracted_path)[1] if extracted_path else {}
    finally:
        if temporary:
            temporary.cleanup()
    if extracted_path:
        for key in extracted.keys() - reference.keys():
            failures.append(f'new source missing from application catalogs: {key}')
    for code in codes:
        root, messages = catalog(ROOT / f'resources/i18n/{code}.ts')
        if root.get('language') != code:
            failures.append(f'{code}: incorrect TS language')
        if messages.keys() != reference.keys():
            failures.append(f'{code}: source key mismatch')
        for key, message in messages.items():
            source = key[1]
            node = message.find('translation')
            translated = ''.join(node.itertext()) if node is not None else ''
            problems = []
            if not translated.strip() or node.get('type') in {'unfinished', 'vanished', 'obsolete'}:
                problems.append('missing or unfinished translation')
            if collections.Counter(TOKENS.findall(source)) != collections.Counter(TOKENS.findall(translated)):
                problems.append('placeholder mismatch')
            if translated == source and source not in SHARED | IDENTICAL.get(code, set()) and not source.startswith('uwfmgr filter enable\n'):
                problems.append('unreviewed untranslated source')
            for literal in LITERALS:
                if literal in source and literal not in translated:
                    problems.append(f'modified technical literal: {literal}')
            if source.startswith('uwfmgr filter enable\n') and translated != source:
                problems.append('modified command sample')
            if source.startswith(('Text files (', 'All files (')):
                if re.findall(r'\([^)]*\)', source) != re.findall(r'\([^)]*\)', translated) or source.count(';;') != translated.count(';;'):
                    problems.append('modified file filter patterns')
            if re.search(r'<(?:p|b|span)\b', source):
                try:
                    if Markup(source).structure != Markup(translated).structure:
                        problems.append('rich-text structure or attributes changed')
                except ValueError as error:
                    problems.append(str(error))
            for problem in problems:
                failures.append(f'{code}: {source[:85]!r}: {problem}')
        print(f'{code}: {len(messages)} application messages')
    qt_directory = ROOT / 'resources/i18n/qt'
    configured_qt = re.search(r'set\(UWF_QT_I18N_LOCALES ([^)]+)\)', cmake).group(1).split()
    if set(configured_qt) != set(codes) or {path.stem.removeprefix('qtbase_') for path in qt_directory.glob('qtbase_*.ts')} != set(codes):
        failures.append('Qt catalogs and configured languages differ')
    _, qt_reference = catalog(qt_directory / 'qtbase_zh_CN.ts')
    # Qt 6.11/6.12 的文件选择框新增了助记键，上游目录尚未更新这两个键。
    qt_local_keys = qt_reference.keys() | {('QFileDialog', '&Look in:', ''), ('QFileDialog', 'Files of &type:', '')}
    for code in sorted(LOCAL_QT_LOCALES):
        root, messages = catalog(qt_directory / f'qtbase_{code}.ts')
        if root.get('language') != code or messages.keys() != qt_local_keys:
            failures.append(f'qtbase_{code}: language or source keys differ from the Qt reference')
        identical = {'OK', 'Alt+Left', 'Alt+Right', 'Alt+Up'} | ({'Drive', 'Folder', 'Alias'} if code == 'id' else set())
        for key, message in messages.items():
            source = key[1]
            translation = message.find('translation')
            translated = ''.join(translation.itertext()) if translation is not None else ''
            if not translated.strip() or translation.get('type') in {'unfinished', 'vanished', 'obsolete'}:
                failures.append(f'qtbase_{code}: missing translation for {source!r}')
            if collections.Counter(TOKENS.findall(source)) != collections.Counter(TOKENS.findall(translated)):
                failures.append(f'qtbase_{code}: placeholder mismatch for {source!r}')
            if source.startswith('<p>Qt is a C++ toolkit'):
                if translated != source:
                    failures.append(f'qtbase_{code}: Qt licensing notice must be preserved verbatim')
            elif translated == source and source not in identical:
                failures.append(f'qtbase_{code}: unreviewed untranslated source {source!r}')
            if collections.Counter(re.findall(r'</?[^>]+>', source)) != collections.Counter(re.findall(r'</?[^>]+>', translated)):
                failures.append(f'qtbase_{code}: rich-text markup changed for {source!r}')
            if source.endswith('(*)') and not translated.endswith('(*)'):
                failures.append(f'qtbase_{code}: file filter pattern changed for {source!r}')
        print(f'qtbase_{code}: {len(messages)} standard widget messages')
    if args.qt_source:
        def signature(node):
            text = node.text if len(node) == 0 else (node.text or '').strip()
            return node.tag, tuple(sorted(node.attrib.items())), text, tuple(signature(child) for child in node)
        for path in sorted((ROOT / 'resources/i18n/qt').glob('qtbase_*.ts')):
            if path.stem.removeprefix('qtbase_') in LOCAL_QT_LOCALES:
                continue
            upstream_name = 'qtbase_pt_BR.ts' if path.name == 'qtbase_pt_PT.ts' else path.name
            upstream = ET.parse(args.qt_source / 'qttranslations/translations' / upstream_name).getroot()
            contexts = {context.findtext('name'): context for context in upstream.findall('context')}
            for context in ET.parse(path).getroot().findall('context'):
                if signature(context) != signature(contexts[context.findtext('name')]):
                    failures.append(f'{path.name}: modified Qt context {context.findtext("name")}')
        if (ROOT / 'resources/i18n/qt/qtbase_pt_BR.ts').read_bytes() != (ROOT / 'resources/i18n/qt/qtbase_pt_PT.ts').read_bytes():
            failures.append('Qt Portuguese catalogs are not identical')
    if failures:
        print('\n'.join(failures), file=sys.stderr)
        return 1
    print(f'{len(codes)} catalogs complete; placeholders, markup, filters and technical literals verified.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
